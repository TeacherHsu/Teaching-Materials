// 每個大項的「學習策略」一句話。
//
// 策略如果只藏在活動裡、只在答錯時出現，學生就只有失敗時看得到，而且不會知道
// 自己練的是什麼方法，也就無法遷移到課本以外。這裡把策略外顯出來：大項開頭
// 先講一次，答錯提示再用**同一套用詞**重述——用詞一致是遷移的前提。
//
// 寫法原則：一句話、講「怎麼做」而不是「要用功」、可以直接對學生念。
const STRATEGY_CARDS = {
  characters: '先看字的左邊或上面，找出部首；再拼拼看注音。',
  vocabulary: '把語詞放回句子裡念一次，再想想它在說什麼。',
  visual_search: '先記住目標字的樣子，再一格一格比對；長得像的要看部首和筆畫哪裡不一樣。',
  idiom_builder: '先想這個成語在講什麼情況，再找出缺的那個字。',
  sentence_practice: '先找出句子的骨架：誰、做什麼，再把其他部分排進去。',
  reading: '一段一段讀，先問每段在講誰、做什麼，再看前後怎麼接起來。',
  main_idea: '問自己一句話：這句話講到整課，還是只講了其中一段？',
  zhuyin_typing: '先聽清楚第一個音，找出聲符；再聽韻母和聲調。',
  word_reading: '先看清楚每一個字，想想在哪裡學過，再一個字一個字念清楚。',
  phrase_builder: '照樣造短語三步驟：不變的字照抄、可以換的格子換上同一類的詞、念念看通不通。',
  polysemy: '把這個字放回整個詞語裡念一次，意思就出來了。',
  polyphones: '同一個字會有不同讀音，要看它和哪個字組成詞語。',
  lookalikes: '兩個字長得像，就比較不一樣的那一部分在哪裡。',
  listening: '聽的時候抓住人物和動作，聽完先在心裡說一次。',
  rhetoric: '看看句子把什麼比成什麼，或是哪些字重複出現。',
  review: '先想想這個字以前在哪一課看過，再看它這次和誰組成詞語。',
};

/** @returns {string|null} 該大項的策略句；沒有定義時回傳 null（不顯示卡片）。 */
export function strategyFor(moduleKey) {
  return STRATEGY_CARDS[moduleKey] || null;
}

export { STRATEGY_CARDS };
