function sentenceFor(term, char) {
  if (sentenceByTerm[term]) return sentenceByTerm[term];
  return `請想一想「${char}」在《${term}》中的意思。`;
}

function buildPolysemy(lesson) {
  return (polysemyRows[lesson] || []).map(([char, term, definition, options], index) => ({
    id: id('polysemy', lesson, index + 1),
    char,
    sentence: sentenceFor(term, char),
    definition,
    options,
    status: PUBLIC_STATUS,
    source: source.polysemy(lesson),
  }));
}

function buildPolysemySenses(lesson) {
  const groups = new Map();
  for (const [char, term, definition] of polysemyRows[lesson] || []) {
    if (!groups.has(char)) groups.set(char, []);
    const senses = groups.get(char);
    if (!senses.some((s) => s.definition === definition)) senses.push({ definition, examples: [term] });
  }
  return [...groups.entries()].map(([char, senses], index) => ({
    id: id('polysemy_sense', lesson, index + 1),
    char,
    senses,
    status: READINGS_STATUS,
    source: source.polysemy(lesson),
  }));
}

function buildPolyphones(lesson) {
  return (polyphoneData[lesson] || []).map((entry, index) => ({
    ...entry,
    id: id('polyphone', lesson, index + 1),
    status: READINGS_STATUS,
    source: source.polyphones(lesson),
  }));
}

function buildListening(lesson) {
  return (listeningData[lesson] || []).map(([question, answer, options, stem], index) => ({
    id: id('listening', lesson, index + 1),
    stem,
    question,
    options,
    answer,
    status: PUBLIC_STATUS,
    source: source.listening(lesson),
  }));
}

function buildRhetoric(lesson) {
  return (rhetoricData[lesson] || []).map(([figure, example, child_note], index) => ({
    id: id('rhetoric', lesson, index + 1),
    figure,
    note: child_note,
    child_note,
    example,
    status: PUBLIC_STATUS,
    source: source.rhetoric(lesson),
  }));
}

function updateModule(lesson, key, ready, note) {
  if (!lesson.modules?.[key]) return;
  lesson.modules[key] = ready
    ? { ...lesson.modules[key], status: 'available', note: undefined }
    : { ...lesson.modules[key], status: 'missing', note };
  if (lesson.modules[key].note === undefined) delete lesson.modules[key].note;
}

for (let lessonNo = 7; lessonNo <= 12; lessonNo += 1) {
  const file = join(dataDir, `lesson${String(lessonNo).padStart(2, '0')}.json`);
  const lesson = JSON.parse(readFileSync(file, 'utf8'));
  lesson.polysemy = buildPolysemy(lessonNo);
  lesson.polysemy_senses = buildPolysemySenses(lessonNo);
  lesson.polyphones = buildPolyphones(lessonNo);
  lesson.listening = buildListening(lessonNo);
  lesson.rhetoric = buildRhetoric(lessonNo);

  updateModule(lesson, 'polysemy', lesson.polysemy.length >= 3, '官方教材未達三題，待補。');
  updateModule(lesson, 'polyphones', lesson.polyphones.length > 0, '本課官方教材未列「認識多音字」。');
  updateModule(lesson, 'listening', lesson.listening.length >= 3, '官方閱讀理解提問未達三題，待補。');
  updateModule(lesson, 'rhetoric', lesson.rhetoric.length >= 3, '官方修辭解析未達三題，待補。');

  writeFileSync(file, `${JSON.stringify(lesson, null, 2)}\n`, 'utf8');
  console.log(`L${String(lessonNo).padStart(2, '0')}: polysemy=${lesson.polysemy.length}, polyphones=${lesson.polyphones.length}, listening=${lesson.listening.length}, rhetoric=${lesson.rhetoric.length}`);
}
