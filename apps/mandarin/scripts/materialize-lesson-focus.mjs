let updated = 0;
for (const [lessonId, focus] of Object.entries(focuses)) {
  const volume = lessonId.slice(0, 7);
  const lessonNo = Number(lessonId.slice(-2));
  const file = path.join(DATA_ROOT, volume, `lesson${String(lessonNo).padStart(2, '0')}.json`);
  if (!fs.existsSync(file)) throw new Error(`課次資料不存在：${lessonId}`);
  const lesson = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (lesson.lesson_id !== lessonId) throw new Error(`課次 ID 不符：${file}`);
  lesson.blurb = focus;
  fs.writeFileSync(file, `${JSON.stringify(lesson, null, 2)}\n`, 'utf8');
  updated += 1;
}

if (updated !== 55) throw new Error(`預期更新 55 課，實際更新 ${updated} 課`);
console.log(`已更新 ${updated} 課首頁學習焦點。`);
