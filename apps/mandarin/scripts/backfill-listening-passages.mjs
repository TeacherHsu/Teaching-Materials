function rewriteOptionText(text) {
  return OPTION_TEXT_REWRITES[text] || text;
}

const LOCKED_LESSONS = new Set(['115AG3H01']);

function filesForLesson(lessonId) {
  const volume = lessonId.slice(0, 7);
  return path.join(dataRoot, volume, `lesson${lessonId.slice(-2)}.json`);
}

function updateLesson(lessonId, passages) {
  const file = filesForLesson(lessonId);
  if (!fs.existsSync(file)) throw new Error(`找不到公開課次資料：${file}`);
  const lesson = JSON.parse(fs.readFileSync(file, 'utf8'));
  let changed = false;
  const g1aItems = G1A_LISTENING[lessonId];
  if (g1aItems && (lesson.listening || []).length === 0) {
    lesson.listening = g1aItems.map((item, index) => ({
      id: `listening:${lessonId}:${String(index + 1).padStart(2, '0')}`,
      stem: item.question,
      question: item.question,
      options: item.options,
      answer: item.answer,
      status: 'approved',
      source: '115G1A／翰林一年上官方教材（09閱讀理解提問；課文逐題回核）',
      passage: item.passage,
    }));
    if (lesson.modules?.listening) {
      lesson.modules.listening.status = 'available';
      lesson.modules.listening.note = '已依官方閱讀理解提問與課文關鍵語句逐題核對。';
    }
    changed = true;
  }
  if (g1aItems && lesson.listening?.length === g1aItems.length) {
    for (const [index, item] of lesson.listening.entries()) {
      if (item.passage !== g1aItems[index].passage) {
        item.passage = g1aItems[index].passage;
        changed = true;
      }
    }
  }
  for (const [index, item] of (lesson.listening || []).entries()) {
    const key = `${lessonId}:${index + 1}`;
    const passage = passages[index];
    if (passage && item.passage !== passage) {
      item.passage = passage;
      changed = true;
    }
    if (ANSWER_FIXES[key] && item.answer !== ANSWER_FIXES[key]) {
      item.answer = ANSWER_FIXES[key];
      changed = true;
    }
    const optionFix = OPTION_FIXES[key];
    if (optionFix && item.options?.includes(optionFix.from)) {
      item.options = item.options.map((option) => option === optionFix.from ? optionFix.to : option);
      changed = true;
    }
    if (Array.isArray(item.options)) {
      const options = item.options.map(rewriteOptionText);
      if (JSON.stringify(options) !== JSON.stringify(item.options)) {
        item.options = options;
        changed = true;
      }
    }
    const rewrittenAnswer = rewriteOptionText(item.answer);
    if (rewrittenAnswer !== item.answer) {
      item.answer = rewrittenAnswer;
      changed = true;
    }
  }
  if (LOCKED_LESSONS.has(lessonId)) {
    for (const item of lesson.listening || []) {
      if (item.status !== 'review_required') {
        item.status = 'review_required';
        changed = true;
      }
    }
    if (lesson.modules?.listening) {
      if (lesson.modules.listening.status !== 'missing') {
        lesson.modules.listening.status = 'missing';
        changed = true;
      }
      const note = '官方課文核對後，現有題目內容與本課課文不相符，待重新編題。';
      if (lesson.modules.listening.note !== note) {
        lesson.modules.listening.note = note;
        changed = true;
      }
    }
  }
  if (changed) fs.writeFileSync(file, `${JSON.stringify(lesson, null, 2)}\n`, 'utf8');
  return changed;
}

let changedLessons = 0;
const lessonIds = new Set([...Object.keys(PASSAGES), ...Object.keys(G1A_LISTENING)]);
for (const lessonId of lessonIds) {
  if (updateLesson(lessonId, PASSAGES[lessonId] || [])) changedLessons += 1;
}
