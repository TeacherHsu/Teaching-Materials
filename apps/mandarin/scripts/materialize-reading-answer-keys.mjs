let updated = 0;
for (const [volumeCode, lessonKeys] of Object.entries(ANSWER_KEYS)) {
  for (const [lessonNumberText, pairs] of Object.entries(lessonKeys)) {
    const lessonNumber = Number(lessonNumberText);
    const file = path.join(DATA_ROOT, volumeCode, `lesson${String(lessonNumber).padStart(2, '0')}.json`);
    if (!fs.existsSync(file)) throw new Error(`缺少課次資料：${volumeCode} 第 ${lessonNumber} 課`);
    const original = fs.readFileSync(file, 'utf8');
    const lesson = JSON.parse(original);
    const questions = lesson.reading_questions || [];
    if (questions.length !== pairs.length) {
      throw new Error(`${volumeCode} 第 ${lessonNumber} 課題數與核對清單不同：${questions.length} !== ${pairs.length}`);
    }
    questions.forEach((question, index) => {
      const [expectedStem, answer] = pairs[index];
      if (question.stem !== expectedStem) {
        throw new Error(`${volumeCode} 第 ${lessonNumber} 課第 ${index + 1} 題題幹變更，請重新核對答案`);
      }
      if (!Array.isArray(question.options) || !question.options.includes(answer)) {
        throw new Error(`${volumeCode} 第 ${lessonNumber} 課第 ${index + 1} 題答案不在選項中：${answer}`);
      }
      question.answer = answer;
      question.answer_source = 'derived:reviewed-reading-question-context';
      updated += 1;
    });
    const next = `${JSON.stringify(lesson, null, 2)}\n`;
    if (next !== original) fs.writeFileSync(file, next, 'utf8');
  }
}

console.log(`已核對並寫入 ${updated} 題閱讀選擇題答案鍵。`);
